"""Minimal ``timm.models.layers`` shim for the vendored WaterMamba architecture.

WaterMamba imports three helpers from ``timm.models.layers``: ``DropPath``,
``to_2tuple`` and ``trunc_normal_``. That module path was removed from timm
somewhere past 0.6.x, and the modern timm package (1.x) cannot even be
installed on this host -- its build backend and runtime dependencies are
served from PyPI's file CDN, which is unreachable here, and it pulls in
``huggingface_hub``/``safetensors`` that a benchmark does not need to score a
convolutional baseline.

Rather than vendor all of timm, this module provides exactly those three
symbols, transcribed verbatim from the timm source (Ross Wightman, Apache-2.0)
that the architecture was written against. Two of the three are trivial -- and
for inference, ``DropPath`` with ``drop_path=0`` is the identity, while
``trunc_normal_`` only runs at construction and is overwritten by the released
checkpoint anyway. ``to_2tuple`` is pure.

The adapter installs this module as ``timm.models.layers`` before importing the
architecture, so the vendored file remains byte-identical to its upstream
release.
"""

from __future__ import annotations

import collections.abc
import math
import warnings
from itertools import repeat

import torch
from torch import nn
from torch.nn.init import _calculate_fan_in_and_fan_out


# ---------------------------------------------------------------- to_2tuple
def _ntuple(n):
    def parse(x):
        if isinstance(x, collections.abc.Iterable) and not isinstance(x, str):
            return tuple(x)
        return tuple(repeat(x, n))
    return parse


to_1tuple = _ntuple(1)
to_2tuple = _ntuple(2)
to_3tuple = _ntuple(3)
to_4tuple = _ntuple(4)
to_ntuple = _ntuple


# ------------------------------------------------------------------ DropPath
def drop_path(x, drop_prob: float = 0., training: bool = False,
              scale_by_keep: bool = True):
    """Drop paths (Stochastic Depth) per sample (when applied in main path of
    residual blocks).
    """
    if drop_prob == 0. or not training:
        return x
    keep_prob = 1 - drop_prob
    shape = (x.shape[0],) + (1,) * (x.ndim - 1)  # work with diff dim tensors
    random_tensor = x.new_empty(shape).bernoulli_(keep_prob)
    if keep_prob > 0.0 and scale_by_keep:
        random_tensor.div_(keep_prob)
    return x * random_tensor


class DropPath(nn.Module):
    """Drop paths (Stochastic Depth) per sample  (when applied in main path of
    residual blocks).
    """

    def __init__(self, drop_prob: float = 0., scale_by_keep: bool = True):
        super(DropPath, self).__init__()
        self.drop_prob = drop_prob
        self.scale_by_keep = scale_by_keep

    def forward(self, x):
        return drop_path(x, self.drop_prob, self.training, self.scale_by_keep)

    def extra_repr(self):
        return f'drop_prob={round(self.drop_prob,3):0.3f}'


# -------------------------------------------------------------- trunc_normal_
def _trunc_normal_(tensor, mean, std, a, b):
    # Method based on https://people.sc.fsu.edu/~jburkardt/presentations/truncated_normal.pdf
    def norm_cdf(x):
        # Computes standard normal cumulative distribution function
        return (1. + math.erf(x / math.sqrt(2.))) / 2.

    if (mean < a - 2 * std) or (mean > b + 2 * std):
        warnings.warn("mean is more than 2 std from [a, b] in nn.init.trunc_normal_. "
                      "The distribution of values may be incorrect.",
                      stacklevel=2)

    # Values are generated by using a truncated uniform distribution and
    # then using the inverse CDF for the normal distribution.
    # Get upper and lower cdf values
    l = norm_cdf((a - mean) / std)
    u = norm_cdf((b - mean) / std)

    # Uniformly fill tensor with values from [l, u], then translate to
    # [2l-1, 2u-1].
    tensor.uniform_(2 * l - 1, 2 * u - 1)

    # Use inverse cdf transform for normal distribution to get truncated
    # standard normal
    tensor.erfinv_()

    # Transform to proper mean, std
    tensor.mul_(std * math.sqrt(2.))
    tensor.add_(mean)

    # Clamp to ensure it's in the proper range
    tensor.clamp_(min=a, max=b)
    return tensor


def trunc_normal_(tensor, mean=0., std=1., a=-2., b=2.):
    r"""Fills the input Tensor with values drawn from a truncated normal
    distribution.

    The values are effectively drawn from the normal distribution
    :math:`\mathcal{N}(\text{mean}, \text{std}^2)` with values outside
    :math:`[a, b]` redrawn until they are within the bounds.
    """
    with torch.no_grad():
        return _trunc_normal_(tensor, mean, std, a, b)


